import {test,expect} from '@playwright/test';
test('iPhone magic items menu supports favorites and persistence',async ({page})=>{
 await page.goto('/four-keeps/');
 await page.getByRole('button',{name:'Settings',exact:true}).click();
 const menu=page.getByRole('button',{name:'Open navigation menu'});
 await menu.click();
 await expect(page.getByRole('navigation',{name:'Primary navigation'})).toBeVisible();
 await page.getByRole('button',{name:'Close navigation menu'}).click({position:{x:300,y:300}});
 await expect(page.getByRole('navigation',{name:'Primary navigation'})).toHaveCount(0);
 await menu.click();
 await page.getByRole('navigation',{name:'Primary navigation'}).getByRole('button',{name:'Developer'}).click();
 const development=page.getByLabel('Development section');
 if(!(await development.getByLabel('Legacy campaign creation').isVisible()))await development.locator('summary').first().click();
 await development.getByLabel('Legacy campaign creation').getByLabel('New campaign name').fill('Wishlist smoke');
 await development.getByLabel('Legacy campaign creation').getByRole('button',{name:'New',exact:true}).click();
 await menu.click();
 await page.getByRole('navigation',{name:'Primary navigation'}).getByRole('button',{name:'Magic Items'}).click();
 await expect(page.getByRole('heading',{name:'Magic Items'})).toBeVisible();
 const compendium=page.getByRole('region',{name:'Magic Item Compendium'});
 const cards=compendium.getByRole('article');
 await expect(cards).toHaveCount(511);
 const descriptions=await compendium.locator('article > p:first-of-type').allTextContents();
 expect(descriptions).toHaveLength(511);
 expect(descriptions.every(description=>description.trim().length>0)).toBe(true);
 const armor=cards.filter({has:page.getByRole('heading',{name:'Armor +1',exact:true})});
 await expect(armor.getByText(/Armor Class/)).toBeVisible();
 const groupFilter=compendium.getByRole('combobox',{name:'Magic item group'});
 const subgroupFilter=compendium.getByRole('combobox',{name:'Magic item subgroup'});
 await expect(subgroupFilter).toBeVisible();
 await expect(compendium.locator('article details')).toHaveCount(0);
 const groupJump=compendium.getByRole('navigation',{name:'Jump to magic item section'});
 const subgroupJump=compendium.getByRole('navigation',{name:'Jump to magic item subgroup'});
 await expect(groupJump.getByRole('button',{name:'Storage and containers'})).toBeVisible();
 await expect(subgroupJump.getByRole('button',{name:'Storage and containers — Containers and storage'})).toBeVisible();
 await groupJump.getByRole('button',{name:'Storage and containers'}).click();
 await expect(compendium.getByRole('heading',{name:'Storage and containers',exact:true})).toBeVisible();
 await subgroupJump.getByRole('button',{name:'Storage and containers — Containers and storage'}).click();
 const storageHeading=compendium.locator('[id^="magic-subgroup-"]').filter({hasText:/^Containers and storage$/}).last();
 await expect(storageHeading).toBeVisible();
 await expect.poll(async()=>storageHeading.evaluate(element=>Math.abs(element.getBoundingClientRect().top)<80)).toBe(true);
 await expect(compendium.locator('article details')).toHaveCount(0);
 await expect(compendium.getByRole('heading',{name:'Weapons',exact:true})).toBeVisible();
 await groupFilter.selectOption('Weapons');
 await expect(compendium.getByRole('heading',{name:'Armor +1',exact:true})).toHaveCount(0);
 await groupFilter.selectOption('All');
 const rarityFilter=compendium.getByRole('combobox',{name:'Magic item rarity'});
 await rarityFilter.selectOption('Rare');
 await expect(compendium.getByRole('article').first().locator('span.text-blue-300')).toHaveText('Rare');
 await rarityFilter.selectOption('All');
 const search=page.getByRole('textbox',{name:'Search magic items'});
 await search.fill('Alchemy Jug');
 const jug=cards.filter({has:page.getByRole('heading',{name:'Alchemy Jug',exact:true})});
 await expect(jug.getByText(/Magic action.*Utilize action.*dawn/)).toBeVisible();
 await expect(jug.getByRole('region',{name:'Alchemy Jug rules and source'})).toHaveCount(0);
 await expect(jug.getByText(/Source: 2024 Dungeon Master/)).toHaveCount(0);
 const liquids=jug.getByRole('table',{name:'Alchemy Jug liquids'});
 await expect(liquids.getByRole('row')).toHaveCount(11);
 await expect(liquids.getByRole('row',{name:'Basic Poison 4 ounces'})).toBeVisible();
 await expect(liquids.getByRole('row',{name:'Salt water 12 gallons'})).toBeVisible();
 await search.fill('Wraps of Unarmed Power');
 const wraps=cards.filter({has:page.getByRole('heading',{name:'+3 Wraps of Unarmed Power',exact:true})});
 await expect(wraps.getByText(/\+3 to Unarmed Strike attack and damage rolls.*Force damage/)).toBeVisible();
 await groupFilter.selectOption('Storage and containers');
 await subgroupFilter.selectOption('Containers and storage');
 await search.fill('Bag of Holding');
 await expect(page.getByRole('heading',{name:'Bag of Holding',exact:true})).toBeVisible();
 await expect(compendium.getByText(/stores up to 500 pounds/)).toBeVisible();
 await page.getByRole('button',{name:'Add Bag of Holding to Wish List'}).click();
 await subgroupFilter.selectOption('All');
 await groupFilter.selectOption('All');
 await page.getByRole('button',{name:'Wish List (1)'}).click();
 await expect(page.getByRole('heading',{name:'Bag of Holding',exact:true})).toBeVisible();
 await expect(compendium.getByText(/stores up to 500 pounds/)).toBeVisible();
 await page.reload();
 await page.getByRole('button',{name:'Campaigns',exact:true}).click();
 await page.getByRole('button',{name:'Continue Adventure'}).click();
 await page.getByRole('button',{name:'Open navigation menu'}).click();
 await page.getByRole('navigation',{name:'Primary navigation'}).getByRole('button',{name:'Magic Items'}).click();
 await page.getByRole('button',{name:'Wish List (1)'}).click();
 await expect(page.getByRole('heading',{name:'Bag of Holding',exact:true})).toBeVisible();
 await expect(compendium.getByText(/stores up to 500 pounds/)).toBeVisible();
 await page.getByRole('button',{name:'Remove Bag of Holding from Wish List'}).click();
 await expect(page.getByText('No matching items.')).toBeVisible();
});
